/// Number of surah units occupying a page (BR-503).
int quranPageParts(int page) => quranPageSurahs[page]?.length ?? 1;

/// All 604 pages expanded into their units, ordered by page then part.
final List<QuranUnit> quranUnits = [
  for (var page = 1; page <= 604; page++)
    for (var i = 0; i < quranPageSurahs[page]!.length; i++)
      QuranUnit(
        page: page,
        partIndex: i + 1,
        surah: quranPageSurahs[page]![i],
      ),
];

/// Units belonging to a page, in part order.
List<QuranUnit> quranUnitsOfPage(int page) =>
    quranUnits.where((u) => u.page == page).toList();

/// Surah of a specific unit on a page (falls back to the first unit).
String quranSurahOf(int page, [int partIndex = 1]) {
  final surahs = quranPageSurahs[page];
  if (surahs == null || surahs.isEmpty) return '—';
  final index = (partIndex - 1).clamp(0, surahs.length - 1);
  return surahs[index];
}

