/// '—' for single pages (before the full page→surah map landed) — resolve
/// those from the registry instead.
String quranDisplaySurah(int page, int partIndex, String stored) {
  final s = stored.trim();
  if (s.isEmpty || s == '—' || s == '-') {
    return quranSurahOf(page, partIndex);
  }
  return s;
}

// ── Juz ranges (604-page Madinah mushaf) ──────────────────────────────────

/// First page of a juz (1..30).
int juzStartPage(int juz) {
  if (juz <= 1) return 1;
  if (juz >= 30) return 582;
  return 22 + (juz - 2) * 20;
}

/// Last page of a juz (1..30).
int juzEndPage(int juz) {
  if (juz <= 1) return 21;
  if (juz >= 30) return 604;
  return juzStartPage(juz) + 19;
}

/// `(first, last)` page range of a juz.
(int, int) juzPageRange(int juz) =>
    (juzStartPage(juz), juzEndPage(juz));

/// Number of pages in a juz.
int juzPageCount(int juz) => juzEndPage(juz) - juzStartPage(juz) + 1;

/// Juz (1..30) that contains a mushaf page (1..604).
int juzOfPage(int page) {
  if (page <= 21) return 1;
  if (page >= 582) return 30;
  return ((page - 22) ~/ 20) + 2;
}